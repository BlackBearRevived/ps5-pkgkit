"""What goes into a package and which size class it declares."""

from __future__ import annotations

from dataclasses import dataclass

from . import paramjson

GENERATED_SCE_SYS_FILES = frozenset({
    "disc_info.dat", "ext_info.dat", "imagedigs.dat", "license.info",
    "license.dat", "playgo-chunk.dat", "playgo-hash-table.dat",
    "playgo-ficm.dat", "playgo-scenario.json", "playgo-manifest.xml",
    "playgo-chunk.crc", "pfsimage.xml", "pfs-region-hints.json", "param.sfo",
    "param_cp_values.json", "pronunciation.sig", "origin-deltainfo.dat",
    "target-deltainfo.dat", "origin-param.json", "target-param.json",
    "origin-relocinfo.dat", "target-relocinfo.dat",
})
GENERATED_ROOT_DIRECTORIES = frozenset({"sce_suppl", "sce_sc"})
PROJECT_SUFFIXES = (".gp4", ".gp5", ".esbak")

MIB = 1024 * 1024
STANDARD_PACKAGE_LIMIT = 162_514_599_936
LARGE_PACKAGE_LV1_LIMIT = 195_878_191_104
ADDCONT_MOUNT_LV2_LIMIT = 97_945_387_008
LARGE_PACKAGE_LV2_FILE_LIMIT = 500_000


def excluded(path: str) -> str | None:
    """Why ``path`` stays out of the package, or ``None`` when it belongs in it."""
    lower = path.lower()
    parts = lower.split("/")
    if len(parts) > 1 and parts[0] in GENERATED_ROOT_DIRECTORIES:
        return "reserved/SDK-generated directory"
    if lower.endswith(PROJECT_SUFFIXES):
        return "build-project file"
    if lower.endswith(".playgo-scenario.json"):
        return "build-project scenario sidecar"
    if len(parts) == 2 and parts[0] == "sce_sys" and parts[1] in GENERATED_SCE_SYS_FILES:
        return "generated by packaging; a stale copy"
    if parts[0] == "sce_sys" and lower.endswith(".auth_info"):
        return "decryption sidecar from an extraction"
    return None


@dataclass(frozen=True, slots=True)
class SizeClass:
    attribute: int
    mount_level: int
    estimated: int


def choose_size_class(unpacked: int, files: int, mount_level: int) -> SizeClass:
    if mount_level > 2:
        raise ValueError(
            f"kernel.addcontMountLevel must be 0, 1 or 2, not {mount_level}"
        )
    allowance = max(512 * MIB, (unpacked + 99) // 100) + files * 4096
    estimated = unpacked + allowance
    level = mount_level
    if level == 2 and estimated > ADDCONT_MOUNT_LV2_LIMIT:
        level = 1
    if level == 1 and estimated > LARGE_PACKAGE_LV1_LIMIT:
        level = 0
    if level == 2 or estimated <= STANDARD_PACKAGE_LIMIT:
        return SizeClass(0, level, estimated)
    if estimated <= LARGE_PACKAGE_LV1_LIMIT:
        return SizeClass(1, level, estimated)
    if files > LARGE_PACKAGE_LV2_FILE_LIMIT:
        raise ValueError(
            f"a package this large holds at most {LARGE_PACKAGE_LV2_FILE_LIMIT} "
            f"files; this one has {files}"
        )
    return SizeClass(2, level, estimated)


def _number_value_span(text: str, key: str) -> tuple[int, int] | None:
    at = text.find(key)
    if at < 0:
        return None
    at += len(key)
    colon = text.find(":", at)
    if colon < 0:
        return None
    start = colon + 1
    while start < len(text) and text[start].isspace():
        start += 1
    end = start
    while end < len(text) and (text[end].isdigit() or text[end] == "-"):
        end += 1
    return (start, end) if end > start else None


def _set_number(data: bytes, key: str, value: int) -> bytes | None:
    text = data.decode("utf-8", "replace")
    span = _number_value_span(text, key)
    if span is None:
        return None
    start, end = span
    raw = text.encode("utf-8")
    return raw[:start] + str(value).encode("ascii") + raw[end:]


def size_class_rewrite(data: bytes, unpacked: int, files: int) -> tuple[bytes, str] | None:
    parsed = paramjson.parse(data)
    if parsed is None:
        return None
    if parsed.get("applicationCategoryType") != 0:
        return None
    kernel = parsed.get("kernel")
    mount_level = 0
    if isinstance(kernel, dict) and isinstance(kernel.get("addcontMountLevel"), int):
        mount_level = kernel["addcontMountLevel"]
    chosen = choose_size_class(unpacked, files, min(mount_level, 255))
    current = parsed.get("attributePub")
    output = data
    changes: list[str] = []
    if not isinstance(current, int) or current != chosen.attribute:
        rewritten = (_set_number(output, '"attributePub"', chosen.attribute)
                     if isinstance(current, int)
                     else paramjson.insert_raw_field(output, "attributePub",
                                                    str(chosen.attribute)))
        if rewritten is None:
            raise ValueError("param.json's attributePub could not be rewritten")
        output = rewritten
        changes.append(f"attributePub={chosen.attribute}")
    if chosen.mount_level != mount_level:
        rewritten = _set_number(output, '"addcontMountLevel"', chosen.mount_level)
        if rewritten is None:
            raise ValueError("param.json's addcontMountLevel could not be rewritten")
        output = rewritten
        changes.append(
            f"kernel.addcontMountLevel {mount_level} -> {chosen.mount_level}"
        )
    if not changes:
        return None
    return output, (
        f"{', '.join(changes)} (estimate {chosen.estimated / (1 << 30):.1f} GiB, "
        f"{files} files)"
    )
